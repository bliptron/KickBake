def require_podman() -> None:
    """Raise BuildError (not FileNotFoundError) when podman is absent.

    main() only catches BuildError, so without this the first
    subprocess.run(["podman", ...]) surfaces as a raw traceback."""
    if shutil.which("podman") is None:
        raise BuildError(
            "podman not found on PATH -- install rootless podman and re-run "
            "(see the README requirements)"
        )


def podman_run(cfg: dict, container_args: list[str],
               stream: bool = False) -> subprocess.CompletedProcess:
    """Run a command in the toolchain container with the repo at /work.

    label=disable avoids recursive SELinux relabeling of the multi-GB
    source ISO on SELinux hosts (the Fedora VM); the container is a
    trusted local build tool.

    stream=True attaches a TTY and inherits stdio so long-running steps
    (dnf downloads) show their live progress meters; the returned
    CompletedProcess carries no captured output."""
    require_podman()
    cmd = [
        "podman", "run", "--rm",
        "--volume", f"{ROOT}:/work",
        "--security-opt", "label=disable",
        "--workdir", "/work",
    ]
    if stream:
        cmd += ["--tty"]
        return subprocess.run(cmd + [cfg["fedora"]["builder_image"],
                                     *container_args])
    return subprocess.run(cmd + [cfg["fedora"]["builder_image"],
                                 *container_args],
                          capture_output=True, text=True)


def ensure_builder_image(cfg: dict, rebuild: bool = False) -> None:
    require_podman()
    image = cfg["fedora"]["builder_image"]
    exists = subprocess.run(
        ["podman", "image", "exists", image], capture_output=True
    ).returncode == 0
    if exists and not rebuild:
        return
    print(f"[image] building toolchain image {image} (first run only)...")
    proc = subprocess.run(
        ["podman", "build", "-t", image, str(ROOT / "podman")]
    )
    if proc.returncode != 0:
        raise BuildError(f"podman build failed for {image}")


def ksvalidator_version(cfg: dict) -> str:
    """Discover the F<release> syntax version from the container's
    ksvalidator itself -- never hardcode it."""
    rel = cfg["fedora"]["release"]
    proc = podman_run(cfg, ["ksvalidator", "--listversions"])
    if proc.returncode != 0:
        raise BuildError(f"ksvalidator --listversions failed:\n{proc.stderr.strip()}")
    versions = [ln.strip() for ln in proc.stdout.splitlines() if ln.strip()]
    want = f"F{rel}"
    if want not in versions:
        raise BuildError(
            f"ksvalidator has no syntax version '{want}'; available: "
            + ", ".join(versions)
        )
    return want


