#!/usr/bin/env python3
"""KickBake builder — embed a Kickstart into a Fedora Plasma ISO.

Principle: Kickstart/ISO = machine birth. Ansible = machine personality.
Nothing post-install lives here.

All Fedora tooling (mkksiso, ksvalidator) runs inside an ephemeral Podman
container built from podman/Containerfile. The host needs only:

    python3 >= 3.11 (stdlib only) and podman

Commands:
    doctor      check host deps, build toolchain image, report tool versions
    verify-iso  sha256 the source ISO against the pinned official hash
    pin-iso     verify a NEW ISO and pin it (source + hash in config;
                user-driven: no download, no discovery)
    flatten     resolve the kickstart %include tree into one self-contained file
    validate    run ksvalidator (pykickstart) inside the container
    build       verify + flatten + validate + mkksiso, then emit output/*.sha256

Usage:
    python3 kickbake.py doctor
    python3 kickbake.py build
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

try:
    import tomllib  # python >= 3.11
except ModuleNotFoundError:  # pragma: no cover - reported by doctor
    tomllib = None

__version__ = "1.0.1"

ROOT = Path(__file__).resolve().parent
DEFAULT_CONFIG = ROOT / "config" / "kickbake.toml"

INCLUDE_RE = re.compile(r"^\s*%include\s+(.+?)\s*$")

# pykickstart's BTRFSData.__eq__ compares ONLY mountpoints, so declaring two
# btrfs volumes (each necessarily "btrfs none --label=... <dev>") trips a
# "duplicate" warning. Verified against pykickstart 3.69 (F44): such files
# parse fully and every volume/subvolume entry survives intact. Anaconda
# consumes the same parse result. If Fedora ever makes this a real error,
# the strict failure path below re-engages automatically.
KNOWN_COSMETIC_WARNINGS = (
    "A btrfs volume with the mountpoint none has already been defined.",
)


class BuildError(RuntimeError):
    """Fatal, user-facing error."""


# --------------------------------------------------------------------------
# configuration
# --------------------------------------------------------------------------

def load_config(path: Path) -> dict:
    if tomllib is None:
        raise BuildError(
            "python3 >= 3.11 is required (stdlib tomllib not available); "
            f"running: {sys.version.split()[0]}"
        )
    try:
        with path.open("rb") as fh:
            cfg = tomllib.load(fh)
    except FileNotFoundError:
        raise BuildError(f"config not found: {path}")
    except tomllib.TOMLDecodeError as exc:
        raise BuildError(f"invalid TOML in {path}: {exc}")
    for section in ("fedora", "iso", "kickstart", "output"):
        if section not in cfg:
            raise BuildError(f"config missing [{section}] section: {path}")
    return cfg


def require_under_root(path: Path, what: str) -> Path:
    """Resolve `path` and refuse anything outside the repository root.

    podman mounts exactly ROOT at /work, so a path outside it can never
    work; the naive alternative (Path.relative_to) raises a bare ValueError,
    which main() does not catch, instead of the clean error the CLI contract
    promises everywhere else."""
    p = path.resolve()
    if p != ROOT and ROOT not in p.parents:
        raise BuildError(
            f"{what} must be inside the repository root ({ROOT}): {path}"
        )
    return p


def repo_path(value: str) -> Path:
    """Resolve a config path against the repository root, contained in it."""
    p = Path(value)
    return require_under_root(p if p.is_absolute() else ROOT / p, "config path")


# --------------------------------------------------------------------------
# pure helpers (unit-tested)
# --------------------------------------------------------------------------

def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def flatten_ks(entry: Path, root: Path | None = None) -> tuple[str, list[str]]:
    """Recursively resolve %include directives.

    Include paths are relative to the tree root (the entry file's parent).
    Returns (flattened_text, trace) where trace lists files in visit order.
    """
    root = (root or entry.parent).resolve()
    trace: list[str] = []
    body = _flatten_file(entry.resolve(), root, [], trace)
    header = [
        "# AUTO-GENERATED by kickbake.py flatten -- DO NOT EDIT.",
        f"# Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"# Entry:     {entry}",
        "# Edit the files under kickstart/ instead, then re-run flatten.",
        "",
    ]
    return "\n".join(header + body) + "\n", trace


def _flatten_file(path: Path, root: Path, stack: list[Path],
                  trace: list[str]) -> list[str]:
    rel = path.relative_to(root)
    if path in stack:
        chain = " -> ".join(str(p.relative_to(root)) for p in stack + [path])
        raise BuildError(f"%include cycle detected: {chain}")
    if not path.is_file():
        raise BuildError(f"%include target not found: {rel} (expected {path})")
    trace.append(f"{'  ' * len(stack)}{rel}")
    out: list[str] = []
    stack.append(path)
    for line in path.read_text(encoding="utf-8").splitlines():
        m = INCLUDE_RE.match(line)
        if not m:
            out.append(line)
            continue
        target = m.group(1).strip().strip("'\"")
        if "://" in target:
            raise BuildError(
                f"{rel}: cannot flatten URL include '{target}' offline "
                "(legacy KICKBOOT token?). Use a path relative to the "
                "kickstart tree root."
            )
        if target.startswith("/"):
            # Runtime include (e.g. /tmp/... generated by %pre on the
            # install machine) -- pass through verbatim, never resolve.
            trace.append(f"{'  ' * len(stack)}{target} (runtime)")
            out.append(line)
            continue
        child = (root / target).resolve()
        if child != root and root not in child.parents:
            raise BuildError(
                f"{rel}: %include '{target}' escapes the kickstart tree "
                f"root ({root})"
            )
        out.append(f"# >>> begin include {target} (from {rel})")
        out.extend(_flatten_file(child, root, stack, trace))
        out.append(f"# <<< end include {target}")
    stack.pop()
    return out


def output_paths(cfg: dict, stamp: str | None = None) -> tuple[Path, Path]:
    """output/fedora-plasma-44-kickbake-26.09.07.iso (+ .ks)

    <name>-<fedora release>-<YY.MM.DD>, .iso and .ks sharing the
    same base. Year-first keeps directory listings chronological. The
    trailing date is today (local time). Same-day rebuilds never
    overwrite: when either file already exists, a -N counter
    (-1, -2, ...) is appended for the pair. `stamp` defaults to today
    (local time); callers that must agree on one date (build) pass it
    explicitly so the filename and the menu title cannot diverge.

    The Fedora release comes from the config, never from the source ISO's
    filename: the file may be renamed freely (verify-iso hashes its
    contents), and a netinst refresh within one release must not change
    the naming scheme."""
    name = cfg["output"].get("name", "fedora-plasma")
    release = cfg["fedora"]["release"]
    outdir = repo_path(cfg["output"].get("dir", "output"))
    if stamp is None:
        stamp = datetime.now().strftime("%y.%m.%d")
    base = f"{name}-{release}-kickbake-{stamp}"
    iso = outdir / f"{base}.iso"
    ks = outdir / f"{base}.ks"
    n = 1
    while iso.exists() or ks.exists():
        iso = outdir / f"{base}-{n}.iso"
        ks = outdir / f"{base}-{n}.ks"
        n += 1
    return iso, ks


def write_checksum_file(iso_path: Path) -> Path:
    digest = sha256_file(iso_path)
    ck_path = iso_path.with_suffix(iso_path.suffix + ".sha256")
    ck_path.write_text(f"{digest}  {iso_path.name}\n", encoding="utf-8")
    return ck_path


