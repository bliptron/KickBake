def cmd_doctor(cfg: dict | None, args: argparse.Namespace) -> int:
    """Report the environment, loading our own config.

    `main` deliberately does not pre-load the config for doctor: a broken
    config must surface as a doctor finding, not abort before the report has
    begun. The incoming `cfg` is therefore ignored (normally None)."""
    ok = True

    def check(label: str, passed: bool, detail: str = "") -> None:
        nonlocal ok
        state = "OK  " if passed else "FAIL"
        print(f"[doctor] {state} {label}" + (f" -- {detail}" if detail else ""))
        ok = ok and passed

    check("python >= 3.11 (tomllib)", tomllib is not None,
          sys.version.split()[0])
    check("podman on PATH", shutil.which("podman") is not None)
    try:
        cfg_path = require_under_root(Path(args.config), "--config")
        cfg = load_config(cfg_path)
        check("config loads", True, str(cfg_path.relative_to(ROOT)))
    except BuildError as exc:
        check("config loads", False, str(exc))
        return 1

    if shutil.which("podman") is None:
        return 1
    try:
        ensure_builder_image(cfg, rebuild=args.rebuild)
        check("toolchain image", True, cfg["fedora"]["builder_image"])
    except BuildError as exc:
        check("toolchain image", False, str(exc))
        return 1

    proc = podman_run(cfg, [
        "bash", "-c",
        "rpm -q lorax pykickstart xorriso isomd5sum && command -v mkksiso ksvalidator",
    ])
    if proc.returncode != 0:
        check("container toolchain", False, (proc.stdout + proc.stderr).strip())
        return 1
    for line in proc.stdout.splitlines():
        if line.startswith("/usr/bin"):
            continue
        print(f"[doctor]      {line}")
    check("container toolchain", True)

    try:
        version = ksvalidator_version(cfg)
        check("ksvalidator syntax version", True, version)
    except BuildError as exc:
        check("ksvalidator syntax version", False, str(exc))
        ok = False

    iso = repo_path(cfg["iso"]["source"])
    check("source ISO present", iso.is_file(),
          str(iso.relative_to(ROOT)) if iso.is_file() else f"missing: {iso}")
    pinned = bool(str(cfg["iso"].get("expected_sha256", "")).strip())
    check("expected_sha256 pinned", pinned,
          "" if pinned else "run `python3 kickbake.py verify-iso` guidance")

    print("[doctor] " + ("all good" if ok else "problems found"))
    return 0 if ok else 1


def cmd_verify_iso(cfg: dict, args: argparse.Namespace) -> int:
    try:
        verify_source_iso(cfg)
        return 0
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


def cmd_flatten(cfg: dict, args: argparse.Namespace) -> int:
    _, flat = output_paths(cfg)
    do_flatten(cfg, flat)
    return 0


def cmd_validate(cfg: dict, args: argparse.Namespace) -> int:
    _, flat = output_paths(cfg)
    if not flat.is_file():
        print("[validate] flat kickstart missing; flattening first")
        flat = do_flatten(cfg, flat)
    try:
        do_validate(cfg, flat)
        return 0
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


def cmd_repo(cfg: dict, args: argparse.Namespace) -> int:
    ensure_builder_image(cfg)
    do_build_repo(cfg)
    return 0


def cmd_build(cfg: dict, args: argparse.Namespace) -> int:
    t0 = time.monotonic()
    ensure_builder_image(cfg)
    verify_source_iso(cfg)
    # One date for the whole build: the output filename, the menu title and
    # the output verification all read this value. Recomputing it in each
    # step made a build that crossed midnight fail verification on a good ISO.
    stamp = datetime.now().strftime("%y.%m.%d")
    out, flat = output_paths(cfg, stamp)
    flat = do_flatten(cfg, flat)
    do_validate(cfg, flat)
    iso = repo_path(cfg["iso"]["source"])
    volid = read_volid(cfg, iso)
    print(f"[compose] source volume id: {volid}")
    stage = out.with_name(out.stem + ".stage.iso")
    try:
        stage = do_mkksiso(cfg, flat, out, stage, volid, stamp)
        out = do_compose_offline(cfg, stage, out, volid)
        do_verify_output(cfg, out, volid, flat, stamp)
    finally:
        # Reclaim the multi-GB intermediate on success AND on failure: a
        # failed build used to leave *.stage.iso behind in output/.
        if stage.exists():
            stage.unlink()
    ck = write_checksum_file(out)
    print(f"[sha256]  wrote {ck.relative_to(ROOT)}")
    print(f"[build]   done in {time.monotonic() - t0:.1f}s -> "
          f"{out.relative_to(ROOT)}")
    return 0


