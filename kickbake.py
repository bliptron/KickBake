def do_flatten(cfg: dict, flat: Path) -> Path:
    entry = repo_path(cfg["kickstart"]["entry"])
    if not entry.is_file():
        raise BuildError(f"kickstart entry not found: {entry}")
    text, trace = flatten_ks(entry)
    flat.parent.mkdir(parents=True, exist_ok=True)
    flat.write_text(text, encoding="utf-8")
    print("[flatten] include tree:")
    for line in trace:
        print(f"          {line}")
    print(f"[flatten] wrote {flat.relative_to(ROOT)}")
    return flat


def classify_ksvalidator(lines: list[str]) -> tuple[list[str], list[str]]:
    """Split ksvalidator output into (cosmetic, non_cosmetic) lines.

    Pure -- no I/O -- so it is unit-tested directly.

    cosmetic     : matches a KNOWN_COSMETIC_WARNINGS pattern (the
                   pykickstart btrfs-volume quirk; see that constant).
    non_cosmetic : everything else except the "Checking kickstart file"
                   progress line, i.e. the output that actually matters.

    A non-zero exit code with non-cosmetic output is a hard failure. A zero
    exit code with non-cosmetic output is a warning that must still be
    shown: dropping it silently hides a future ksvalidator complaint whose
    exit code we did not anticipate.
    """
    cosmetic = [ln for ln in lines
                if any(pat in ln for pat in KNOWN_COSMETIC_WARNINGS)]
    non_cosmetic = [ln for ln in lines
                    if ln not in cosmetic
                    and not ln.startswith("Checking kickstart file")]
    return cosmetic, non_cosmetic


def do_validate(cfg: dict, flat: Path) -> None:
    version = ksvalidator_version(cfg)
    rel = flat.relative_to(ROOT)
    print(f"[validate] ksvalidator -v {version} {rel}")
    # Runtime includes (%pre-generated) only exist on the install machine;
    # strip them before validating the rest of the file.
    script = ("sed '/^%include \\/tmp\\//d' /work/" + str(rel)
              + " > /tmp/vflat.ks && ksvalidator -v " + version
              + " /tmp/vflat.ks")
    proc = podman_run(cfg, ["bash", "-c", script])
    lines = [ln.strip() for ln in (proc.stdout + proc.stderr).splitlines()
             if ln.strip()]
    cosmetic, non_cosmetic = classify_ksvalidator(lines)
    if proc.returncode != 0 and non_cosmetic:
        raise BuildError("kickstart validation failed:\n"
                         + "\n".join(non_cosmetic))
    for ln in non_cosmetic:
        print(f"[validate] NOTE ksvalidator output (exit 0): {ln}")
    for ln in cosmetic:
        print(f"[validate] NOTE known-cosmetic warning (see kickbake.py): {ln}")
    print("[validate] OK"
          + (" (known-cosmetic warnings ignored)" if cosmetic else ""))


def verify_source_iso(cfg: dict) -> str:
    """Returns the computed digest. Raises on mismatch. Prints guidance
    when the expected hash is not pinned yet."""
    iso = repo_path(cfg["iso"]["source"])
    if not iso.is_file():
        raise BuildError(f"source ISO not found: {iso}")
    expected = str(cfg["iso"].get("expected_sha256", "")).strip().lower()
    print(f"[verify] sha256 {iso.relative_to(ROOT)} "
          f"({iso.stat().st_size / 2**30:.2f} GiB)")
    actual = sha256_file(iso)
    if not expected:
        print(f"[verify] computed: {actual}")
        raise BuildError(
            "expected_sha256 is not pinned in config/kickbake.toml. Take the "
            "official value from Fedora's CHECKSUM file for this ISO and "
            "set it, then re-run."
        )
    if actual != expected:
        raise BuildError(
            f"checksum mismatch!\n  expected: {expected}\n  actual:   {actual}"
        )
    print(f"[verify] OK ({actual})")
    return actual


def _official_checksum(value: str, iso_name: str) -> str:
    """Accepts a bare sha256 or the path of a Fedora-style CHECKSUM file
    (lines like: SHA256 (name.iso) = <hash>). Returns the lowercase hash,
    or raises BuildError."""
    path = Path(value)
    if path.is_file():
        for line in path.read_text(
                encoding="utf-8", errors="replace").splitlines():
            m = re.match(r"SHA256\s*\((.+?)\)\s*=\s*([0-9a-fA-F]{64})\s*$",
                         line.strip())
            if m and m.group(1) == iso_name:
                return m.group(2).lower()
        raise BuildError(
            f"pin-iso: no SHA256 entry for '{iso_name}' in {path}")
    value = value.strip().lower()
    if re.fullmatch(r"[0-9a-f]{64}", value):
        return value
    raise BuildError(
        "pin-iso: --checksum must be a sha256 hash or a CHECKSUM file path")


def cmd_pin_iso(cfg: dict, args: argparse.Namespace) -> int:
    """pin-iso <new-iso> --checksum <sha256|CHECKSUM-file>

    User-driven pinning of a NEW source ISO: verifies it against the
    OFFICIAL checksum, copies it into assets/, and rewrites exactly two
    lines of the config ([iso] source + expected_sha256). No network,
    no discovery. The previous ISO stays in assets/ for manual removal."""
    new_iso = Path(args.iso).resolve()
    if not new_iso.is_file():
        raise BuildError(f"pin-iso: file not found: {new_iso}")
    if new_iso.suffix.lower() != ".iso":
        raise BuildError(f"pin-iso: not an .iso file: {new_iso.name}")
    official = _official_checksum(args.checksum, new_iso.name)
    actual = sha256_file(new_iso).lower()
    if actual != official:
        raise BuildError(
            "pin-iso: checksum mismatch vs the official value -- refusing "
            f"to pin.\n  official: {official}\n  computed: {actual}")
    dest = ROOT / "assets" / new_iso.name
    if dest.resolve() != new_iso:
        shutil.copy2(new_iso, dest)
    config_path = Path(args.config).resolve()
    text = config_path.read_text(encoding="utf-8")
    # Replacement callables, never f-string replacements: re.subn interprets
    # backslash escapes in a replacement string, so a filename containing
    # \1 or \g<...> would corrupt the config (or raise) instead of being
    # written literally.
    text, n_source = re.subn(r'(?m)^source = ".*"$',
                             lambda m: f'source = "assets/{new_iso.name}"',
                             text)
    text, n_hash = re.subn(r'(?m)^expected_sha256 = ".*"$',
                           lambda m: f'expected_sha256 = "{actual}"', text)
    if n_source != 1 or n_hash != 1:
        raise BuildError(
            f"pin-iso: config update unsafe (source matches: {n_source}, "
            f"hash matches: {n_hash}) -- nothing was written.")
    config_path.write_text(text, encoding="utf-8")
    print(f"[pin-iso] pinned {new_iso.name}")
    print(f"[pin-iso]   sha256: {actual}")
    if dest.resolve() != new_iso:
        print(f"[pin-iso]   installed: {dest}")
        print(f"[pin-iso]   note: the original file remains at {new_iso} "
              "-- remove it manually if unwanted")
    print("[pin-iso] next: python3 kickbake.py verify-iso, then build")
    return 0


def read_volid(cfg: dict, iso: Path) -> str:
    """Read the ISO's volume id via xorriso in the container."""
    rel = iso.relative_to(ROOT)
    proc = podman_run(cfg, [
        "bash", "-c",
        "xorriso -indev /work/" + str(rel) + " 2>&1 | "
        "sed -n \"s/^Volume id *: '\\(.*\\)'$/\\1/p\"",
    ])
    volid = proc.stdout.strip()
    if not volid:
        raise BuildError(f"could not read volume id of {rel}")
    return volid


def do_mkksiso(cfg: dict, flat: Path, out: Path, stage: Path,
               volid: str, stamp: str) -> Path:
    """mkksiso stage: embed kickstart + offline repo, add kernel args.
    Returns the STAGE iso; ESP rebuild happens in do_compose_offline."""
    iso = repo_path(cfg["iso"]["source"])
    out.parent.mkdir(parents=True, exist_ok=True)
    for p in (out, stage):
        if p.exists():
            p.unlink()
    repo = repo_path(cfg["build"].get("repo_dir", "cache/repo"))
    if not (repo / ".done").is_file():
        raise BuildError(
            f"offline repo not ready: {repo.relative_to(ROOT)}/.done missing "
            "(build cache/repo first -- see README)"
        )
    cmd = ["mkksiso", "--ks", f"/work/{flat.relative_to(ROOT)}"]
    cmd += ["-a", f"/work/{repo.relative_to(ROOT)}"]
    cmd += ["-c", f"inst.repo=hd:LABEL={volid}:/repo"]
    # Menu title brand: KickBake <build date YY.MM.DD>, matching the dated
    # output name, e.g. "Install Fedora 44 - KickBake 26.09.14". The typed
    # confirmation and GRUB auth live in compose-offline.sh hardening, not
    # the title. `stamp` is computed once by cmd_build so the title, the
    # output filename and the output verification cannot straddle midnight.
    rel = cfg["fedora"]["release"]
    cmd += ["-R", f"Install Fedora {rel}",
            f"Install Fedora {rel} - KickBake {stamp}"]
    if cfg.get("build", {}).get("skip_mkefiboot", False):
        cmd.append("--skip-mkefiboot")
    cmd += [
        f"/work/{iso.relative_to(ROOT)}",
        f"/work/{stage.relative_to(ROOT)}",
    ]
    proc = podman_run(cfg, cmd)
    if proc.returncode != 0:
        detail = (proc.stdout + proc.stderr).strip()
        raise BuildError(f"mkksiso failed:\n{detail}")
    if not stage.is_file():
        raise BuildError(f"mkksiso reported success but {stage} is missing")
    print(f"[mkksiso] stage {stage.relative_to(ROOT)} "
          f"({stage.stat().st_size / 2**30:.2f} GiB)")
    return stage


def do_compose_offline(cfg: dict, stage: Path, out: Path,
                       volid: str) -> Path:
    """Rebuild the embedded ESP rootlessly (mkfs.vfat -C + mcopy +
    xorriso append_partition) so UEFI boots see the kickstart args."""
    if out.exists():
        out.unlink()
    grub_pw = os.environ.get("KICKBAKE_GRUB_PW", "kickbake")
    proc = podman_run(cfg, [
        "bash", "/work/podman/compose-offline.sh",
        f"/work/{stage.relative_to(ROOT)}",
        f"/work/{out.relative_to(ROOT)}",
        volid,
        grub_pw,
    ])
    if proc.returncode != 0:
        detail = (proc.stdout + proc.stderr).strip()
        raise BuildError(f"compose-offline failed:\n{detail}")
    if not out.is_file():
        raise BuildError(f"compose-offline reported success but {out} missing")
    print(f"[compose] wrote {out.relative_to(ROOT)} "
          f"({out.stat().st_size / 2**30:.2f} GiB)")
    return out


def do_build_repo(cfg: dict) -> None:
    """Build the offline KDE repository into cache/repo (Packages/ +
    repodata/ + .done marker). Downloads the @<group> closure once.

    Critical: repodata is generated WITH Fedora's comps/group metadata --
    without it Anaconda cannot resolve @^kde-desktop/@core at install time
    ("No group metadata available", "0 packages selected"). The repo is
    then self-verified by resolving the group against ONLY this repo."""
    repo = repo_path(cfg["build"].get("repo_dir", "cache/repo"))
    rel = repo.relative_to(ROOT)
    # Anaconda resolves the environment AND unconditionally adds @core
    # (LOG-FINDINGS: "No match for group package: audit/dnf5/..."), so the
    # closure and the self-verification must both cover the same spec.
    groups = cfg["build"].get("repo_groups", "kde-desktop core standard")
    extras = cfg["build"].get("repo_extra_packages", "kernel")
    release = cfg["fedora"]["release"]
    base = cfg["fedora"].get(
        "everything_base",
        "https://dl.fedoraproject.org/pub/fedora/linux/releases/"
        f"{release}/Everything/x86_64/os",
    )
    script = "\n".join([
        "set -e",
        f"if [ -e /work/{rel}/.done ]; then echo '[repo] already built'; exit 0; fi",
        f"mkdir -p /work/{rel}/Packages /work/cache/dnf-cache",
        "# 1. official Fedora comps (group + environment definitions)",
        f"curl -fsSL {base}/repodata/repomd.xml -o /tmp/repomd.xml",
        "COMPS=$(grep -o 'href=\"repodata/[^\"]*comps[^\"]*\"' /tmp/repomd.xml "
        "| head -1 | cut -d'\"' -f2)",
        "test -n \"$COMPS\"",
        f"curl -fsSL {base}/$COMPS -o /tmp/comps.comp",
        "case \"$COMPS\" in"
        " *.gz) gunzip -c /tmp/comps.comp > /tmp/comps.xml ;;"
        " *.zst) zstd -dc /tmp/comps.comp > /tmp/comps.xml ;;"
        " *.xz) xz -dc /tmp/comps.comp > /tmp/comps.xml ;;"
        " *) cp /tmp/comps.comp /tmp/comps.xml ;; esac",
        "test -s /tmp/comps.xml",
        "# 2. package closure for the requested environment",
        f"dnf -y -q --releasever={release} --use-host-config "
        "--installroot=/tmp/void --setopt=cachedir=/work/cache/dnf-cache "
        f"group install {groups} --downloadonly",
        f"dnf -y -q --releasever={release} --use-host-config "
        "--installroot=/tmp/void --setopt=cachedir=/work/cache/dnf-cache "
        f"install {extras} --downloadonly",
        f"find /work/cache/dnf-cache -name '*.rpm' -exec mv {{}} "
        f"/work/{rel}/Packages/ \\;",
        "# 2b. prune superseded versions: keep only the newest rpm per name",
        "# ${stem%-*-*} assumes NEVRA name-[epoch:]version-release, so an",
        "# epoch (name-1:1.2-3) would stay in the key and two rpms could look",
        "# like different names. Harmless today; revisit if epochs become common.",
        f"cd /work/{rel}/Packages",
        "declare -A newest=()",
        "for f in *.rpm; do",
        "    [ -e \"$f\" ] || continue",
        "    stem=\"${f%.rpm}\"; name=\"${stem%-*-*}\"",
        "    [ -n \"$name\" ] || continue",
        "    newest[$name]=$(printf '%s\\n%s\\n' \"${newest[$name]:-}\" \"$f\" "
        "| sort -V | tail -n 1)",
        "done",
        "for f in *.rpm; do",
        "    stem=\"${f%.rpm}\"; name=\"${stem%-*-*}\"",
        "    [ \"${newest[$name]:-}\" = \"$f\" ] || rm -f -- \"$f\"",
        "done",
        "cd /work",
        "# Anaconda requires the kernel package itself (F41+: not in comps)",
        f"test -n \"$(ls /work/{rel}/Packages/kernel-[0-9]*.rpm 2>/dev/null)\"",
        "# 3. metadata WITH comps",
        "dnf -q -y install createrepo_c >/dev/null 2>&1",
        f"createrepo_c --groupfile=/tmp/comps.xml /work/{rel}",
        "# 4. self-verify: resolve the group against ONLY this repo",
        # Both verify passes reuse the persistent /work cache; only the
        # installroots must exist. (/tmp/verify-cache was never referenced.)
        f"mkdir -p /tmp/verify /tmp/verify2",
        f"dnf -y -q --disablerepo='*' --repofrompath=kb,/work/{rel} "
        f"--releasever={release} --installroot=/tmp/verify "
        f"--setopt=cachedir=/work/cache/dnf-cache group install {groups} "
        "--downloadonly",
        f"dnf -y -q --disablerepo='*' --repofrompath=kb,/work/{rel} "
        f"--releasever={release} --installroot=/tmp/verify2 "
        f"--setopt=cachedir=/work/cache/dnf-cache install {extras} "
        "--downloadonly",
        # set -e makes a failed resolve fatal; step 2 moved every rpm out
        # of the cache, so these passes repopulate it from the local repo
        # (fast, no network) -- this check proves they actually resolved.
        "test -n \"$(find /work/cache/dnf-cache -name '*.rpm' | head -1)\"",
        f"touch /work/{rel}/.done",
        f"echo \"[repo] ready + comps + self-verified: "
        f"$(ls /work/{rel}/Packages | wc -l) packages\"",
    ])
    # Stream: the dnf download meters and every step boundary render live
    # (this is the longest step of the build -- silent is unacceptable).
    proc = podman_run(cfg, ["bash", "-c", script], stream=True)
    if proc.returncode != 0 or not (repo / ".done").is_file():
        raise BuildError(
            "offline repo build failed -- see the live output above")


def do_verify_output(cfg: dict, out: Path, volid: str, ks: Path,
                     stamp: str) -> None:
    """Prove the composed ISO is kickstart-enabled, self-contained and
    bootable: the tree grub.cfg (BIOS + UEFI copies) carries
    inst.ks/inst.repo; the HIDDEN ESP (appended GPT partition 2) carries
    them too; /repo/repodata and the kickstart exist in the tree; El
    Torito records survived. Both UEFI menus must be lean (no media
    test) and carry the KickBake <date> title."""
    rel = out.relative_to(ROOT)
    script = (
        "V=/work/" + str(rel) + "; "
        "xorriso -osirrox on -indev $V -extract /boot/grub2/grub.cfg "
        "/tmp/menu.cfg >/dev/null 2>&1 && "
        "grep -q 'requires UEFI' /tmp/menu.cfg && echo TREE_HALT_OK; "
        "xorriso -osirrox on -indev $V -extract /EFI/BOOT/grub.cfg "
        "/tmp/efi.cfg >/dev/null 2>&1 && "
        "grep -q 'inst.ks=' /tmp/efi.cfg && "
        "grep -q 'inst.repo=' /tmp/efi.cfg && echo EFI_ARGS_OK; "
        "L=$(xorriso -indev $V 2>&1 | "
        "grep -oE 'EFI image start and load size: [0-9]+' | "
        "grep -oE '[0-9]+$'); "
        "dd if=$V of=/tmp/esp.img bs=2048 skip=$L count=20480 status=none; "
        "mtype -i /tmp/esp.img ::/EFI/BOOT/grub.cfg > /tmp/esp.cfg 2>/dev/null; "
        "grep -q 'inst.ks=' /tmp/esp.cfg && "
        "grep -q 'inst.repo=' /tmp/esp.cfg && echo ESP_ARGS_OK; "
        "grep -q 'KickBake " + stamp + "' /tmp/esp.cfg && echo TITLE_OK; "
        "grep -q 'Test this media' /tmp/esp.cfg || echo NO_TEST_ENTRY; "
        "grep -q 'superusers=\"kickbake\"' /tmp/esp.cfg && "
        "grep -q 'password_pbkdf2' /tmp/esp.cfg && echo GRUB_AUTH_OK; "
        "grep -q 'KickBake " + stamp + "' /tmp/efi.cfg && echo EFI_TITLE_OK; "
        "grep -q 'Test this media' /tmp/efi.cfg || echo EFI_NO_TEST_ENTRY; "
        "xorriso -indev $V -find /repo/repodata/repomd.xml 2>/dev/null "
        "| grep -q repomd && echo REPO_OK; "
        "xorriso -indev $V -find /repo/repodata -name '*comps*' 2>/dev/null "
        "| grep -q comps && echo COMPS_OK; "
        "xorriso -indev $V -find /" + ks.name + " 2>/dev/null "
        "| grep -q " + ks.name + " && echo KS_OK; "
        "xorriso -indev $V 2>&1 | grep -q 'El Torito' && echo ELTORITO_OK"
    )
    proc = podman_run(cfg, ["bash", "-c", script])
    text = proc.stdout + proc.stderr
    checks = {
        "BIOS tree carries the UEFI-required halt entry": "TREE_HALT_OK" in text,
        "tree UEFI grub.cfg carries inst.ks + inst.repo": "EFI_ARGS_OK" in text,
        "hidden ESP grub.cfg carries inst.ks + inst.repo": "ESP_ARGS_OK" in text,
        "/repo/repodata/repomd.xml present": "REPO_OK" in text,
        "comps group metadata in /repo/repodata": "COMPS_OK" in text,
        "kickstart file present in tree": "KS_OK" in text,
        "El Torito boot records present": "ELTORITO_OK" in text,
        f"ESP menu title carries KickBake {stamp}": "TITLE_OK" in text,
        "no 'Test this media' entry in ESP menu": "NO_TEST_ENTRY" in text,
        "GRUB auth: superusers + pbkdf2 pin the installer entry": "GRUB_AUTH_OK" in text,
        f"tree UEFI menu title carries KickBake {stamp}": "EFI_TITLE_OK" in text,
        "no 'Test this media' entry in tree UEFI menu": "EFI_NO_TEST_ENTRY" in text,
    }
    failed = [name for name, ok in checks.items() if not ok]
    if failed:
        raise BuildError(
            "output ISO verification failed: " + "; ".join(failed)
            + f"\ncontainer output:\n{text.strip()}"
        )
    print("[verify-out] tree+ESP kernel args, /repo repodata+comps, ks file, "
          "El Torito records: OK")


