DISPATCH = {
    "doctor": cmd_doctor,
    "verify-iso": cmd_verify_iso,
    "pin-iso": cmd_pin_iso,
    "flatten": cmd_flatten,
    "validate": cmd_validate,
    "repo": cmd_repo,
    "build": cmd_build,
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="kickbake.py",
        description="Bake a Kickstart into a Fedora Plasma ISO (via Podman).",
    )
    parser.add_argument("--version", action="version",
                        version=f"KickBake {__version__}")
    parser.add_argument("--config", default=str(DEFAULT_CONFIG),
                        help="path to kickbake.toml (default: config/kickbake.toml)")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("doctor", help="check environment and toolchain")
    p.add_argument("--rebuild", action="store_true",
                   help="force-rebuild the toolchain container image")

    sub.add_parser("repo", help="build the offline KDE repo into cache/repo")
    sub.add_parser("verify-iso", help="sha256 the source ISO vs pinned hash")
    p = sub.add_parser("pin-iso",
                       help="verify a NEW ISO against the official checksum "
                            "and pin it (config updated)")
    p.add_argument("iso", help="path to the new source ISO")
    p.add_argument("--checksum", required=True,
                   help="official sha256, or a Fedora-style CHECKSUM file")
    sub.add_parser("flatten", help="resolve the %%include tree to one file")
    sub.add_parser("validate", help="run ksvalidator in the container")
    sub.add_parser("build", help="full workflow: verify->flatten->validate->mkksiso")

    args = parser.parse_args(argv)
    try:
        if args.command == "doctor":
            # doctor loads its own config and reports a broken one; a
            # pre-load here would abort before that report could start.
            return DISPATCH[args.command](None, args)
        # Container-visible paths live under ROOT (podman mounts it at
        # /work), so the config must too. Resolve and check here so every
        # command reports it the same clean way.
        cfg_path = require_under_root(Path(args.config), "--config")
        args.config = str(cfg_path)
        cfg = load_config(cfg_path)
        return DISPATCH[args.command](cfg, args)
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
